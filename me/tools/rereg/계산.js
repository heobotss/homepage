        첫결제: 첫결제, 마지막결제: 마지막결제,
        사이클: 사이클, 순매출: 순매출,
        재등록함: 재등록함, 첫판정끝: 첫판정끝,
        객단가: Math.round(순매출 / 사이클),
        등급: (순매출 >= 설정.VIP기준) ? 'VIP' : '일반',
